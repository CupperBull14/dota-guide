/**
 * Данные интерактивной карты.
 * Карта стилизованная: система координат 0–1000 по обеим осям,
 * Свет (Radiant) — внизу слева, Тьма (Dire) — вверху справа,
 * река идёт по диагонали из левого верхнего угла в правый нижний.
 * Положение объектов показано схематично, а не до пикселя.
 * Тайминги — для патча PATCH из constants.ts.
 */

export type Side = 'radiant' | 'dire' | 'neutral';

export interface MapZone {
  id: string;
  name: string;
  side: Side;
  /** Тип области: площадь (polygon) или линия (широкая кликабельная полоса). */
  kind: 'area' | 'lane';
  /** Точки «x,y x,y …» для polygon или d для path линии. */
  shape: string;
  /** Где показать подпись. */
  label: { x: number; y: number };
  summary: string;
  details: string[];
  tips: string[];
}

export type MarkerType =
  | 'power-rune'
  | 'bounty-rune'
  | 'water-rune'
  | 'shrine'
  | 'roshan'
  | 'tormentor'
  | 'shop'
  | 'lotus'
  | 'observer'
  | 'sentry';

export type MapTab = 'runes' | 'wards' | 'rotations';

export interface MapMarker {
  id: string;
  type: MarkerType;
  x: number;
  y: number;
  name: string;
  /** Короткая строка для тултипа (обычно тайминг). */
  short: string;
  description: string;
  /** На каких вкладках виден маркер. Пусто — виден всегда. */
  tabs: MapTab[];
}

export interface MarkerTypeMeta {
  label: string;
  color: string;
  /** Символ внутри маркера. */
  glyph: string;
}

